defmodule Gitspace.Direnv do
  @moduledoc """
  Generates `.envrc` files that let direnv load a gitspace environment.

  The generated file evaluates `gitspace env --shell`, so the resolved values
  are never copied into the repository. A marker comment distinguishes
  generated files from user-written `.envrc` files; only generated files are
  overwritten without `--force`.
  """

  alias Gitspace.{Checkouts, Config, Env, Error, Projects, Targets, Workspaces}

  @marker "# Generated by gitspace. Do not edit."

  @type plan :: %{target: String.t(), path: Path.t(), body: String.t()}

  @doc "Builds one or more `.envrc` plans for a target."
  @spec plans(Config.t(), String.t(), keyword()) :: {:ok, [plan()]} | {:error, Error.t()}
  def plans(%Config{} = config, target, opts \\ []) do
    with {:ok, targets} <- targets(config, target, opts),
         {:ok, plans} <- build(config, targets) do
      {:ok,
       plans
       |> Enum.reverse()
       |> Enum.uniq_by(& &1.path)}
    end
  end

  @doc "Writes a generated `.envrc`, respecting the marker and `--force`."
  @spec write(plan(), keyword()) :: {:ok, plan()} | {:error, Error.t()}
  def write(%{path: path, body: body} = plan, opts \\ []) do
    with :ok <- writable(path, opts),
         :ok <- maybe_write(path, body, opts) do
      {:ok, plan}
    end
  end

  @doc "Whether a file is one of ours."
  @spec generated?(Path.t()) :: boolean()
  def generated?(path) do
    case File.read(path) do
      {:ok, body} -> String.contains?(body, @marker)
      {:error, _} -> false
    end
  end

  defp targets(config, target, opts) do
    cond do
      opts[:all] ->
        projects = Enum.map(Projects.list(config), &"project:#{&1.name}")
        workspaces = Enum.map(Workspaces.list(config), & &1.name)
        checkouts = Enum.map(Checkouts.list(config), & &1.path)

        {:ok, projects ++ workspaces ++ checkouts}

      opts[:members] ->
        member_targets(config, target)

      true ->
        {:ok, [target]}
    end
  end

  defp member_targets(config, target) do
    case Targets.resolve(config, target) do
      {:ok, {:workspace, workspace}} ->
        members =
          Enum.map(workspace.members, fn member ->
            "#{workspace.name}:#{member_name(member)}"
          end)

        {:ok, [target | members]}

      {:ok, _other} ->
        {:error, Error.new(:usage, "--members needs a workspace target")}

      {:error, error} ->
        {:error, error}
    end
  end

  defp build(config, targets) do
    Enum.reduce_while(targets, {:ok, []}, fn target, {:ok, plans} ->
      case Env.resolve(config, target) do
        {:ok, resolved} ->
          plan = %{
            target: target,
            path: Path.join(resolved.path, ".envrc"),
            body: body(resolved)
          }

          {:cont, {:ok, [plan | plans]}}

        {:error, error} ->
          {:halt, {:error, error}}
      end
    end)
  end

  defp body(resolved) do
    watch =
      Enum.map(resolved.watch, fn path ->
        "watch_file #{shell_quote(path)}"
      end)

    Enum.join(
      [
        @marker,
        "# Environment for this directory, resolved by gitspace.",
        "eval \"$(gitspace env --shell)\""
      ] ++ watch ++ [""],
      "\n"
    )
  end

  defp member_name(member) do
    member.name ||
      (member.checkout && member.checkout.repository && member.checkout.repository.slug)
  end

  defp writable(path, opts) do
    case File.read(path) do
      {:ok, body} ->
        cond do
          String.contains?(body, @marker) ->
            :ok

          opts[:force] ->
            :ok

          true ->
            {:error,
             Error.new(:refused, "#{path} exists and was not generated by gitspace",
               hint: "re-run with --force to replace it"
             )}
        end

      {:error, :enoent} ->
        :ok

      {:error, reason} ->
        {:error,
         Error.new(:error, "cannot read #{path}", hint: :file.format_error(reason) |> to_string())}
    end
  end

  defp maybe_write(_path, _body, dry_run: true), do: :ok

  defp maybe_write(path, body, _opts) do
    File.mkdir_p!(Path.dirname(path))
    File.write!(path, body)
    :ok
  rescue
    error ->
      {:error, Error.new(:error, "cannot write #{path}", hint: Exception.message(error))}
  end

  defp shell_quote(value) do
    "'" <> String.replace(value, "'", "'\\''") <> "'"
  end
end
