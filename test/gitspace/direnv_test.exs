defmodule Gitspace.DirenvTest do
  use Gitspace.IndexCase, async: false

  alias Gitspace.{Config, Create, Direnv, Fixtures, Projects, Repos}

  setup %{config: config} do
    :ok = Config.save(config)
    previous = System.get_env("GITSPACE_CONFIG")
    System.put_env("GITSPACE_CONFIG", config.path)
    System.delete_env("GITSPACE_DATA")
    System.delete_env("GITSPACE_PROJECTS_ROOT")

    on_exit(fn ->
      if previous do
        System.put_env("GITSPACE_CONFIG", previous)
      else
        System.delete_env("GITSPACE_CONFIG")
      end

      System.delete_env("GITSPACE_DATA")
      System.delete_env("GITSPACE_PROJECTS_ROOT")
    end)

    source = Fixtures.source_repo!()
    {:ok, _} = Repos.add(config, Fixtures.repo_url(source), name: "a")
    {:ok, _} = Projects.create(config, "demo", repo: ["a"])
    {:ok, _} = Create.co(config, "demo", "main", topic: "dev")

    project_path = Path.join(config.projects_root, "demo")
    workspace_path = Path.join([config.projects_root, "demo", "dev"])
    checkout_path = Path.join([config.projects_root, "demo", "dev", "a"])

    File.write!(Path.join(project_path, ".env"), "FOO=project\n")
    File.write!(Path.join(project_path, ".env.secrets"), "TOKEN=shh\n")
    File.write!(Path.join(checkout_path, ".env"), "FOO=repo\n")
    File.write!(Path.join(checkout_path, ".env.local"), "LOCAL=yes\n")

    {:ok,
     config: config,
     project_path: project_path,
     workspace_path: workspace_path,
     checkout_path: checkout_path}
  end

  test "renders an .envrc that evaluates gitspace and watches its files", %{
    config: config,
    project_path: project_path,
    checkout_path: checkout_path
  } do
    assert {:ok, [plan]} = Direnv.plans(config, "demo@dev:a")

    assert plan.path == Path.join(checkout_path, ".envrc")
    assert plan.body =~ "# Generated by gitspace. Do not edit."
    assert plan.body =~ ~s{eval "$(gitspace env --shell)"}
    assert plan.body =~ Path.join(project_path, ".env")
    assert plan.body =~ Path.join(project_path, ".env.secrets")
    assert plan.body =~ Path.join(checkout_path, ".env")
    assert plan.body =~ Path.join(checkout_path, ".env.local")
  end

  test "writes, refreshes and refuses a hand-written .envrc", %{config: config} do
    assert {:ok, [plan]} = Direnv.plans(config, "demo@dev:a")

    assert {:ok, _} = Direnv.write(plan, dry_run: true)
    refute File.exists?(plan.path)

    assert {:ok, _} = Direnv.write(plan)
    assert File.read!(plan.path) == plan.body

    assert {:ok, _} = Direnv.write(plan)

    File.write!(plan.path, "# hand-written\n")
    assert {:error, error} = Direnv.write(plan)
    assert error.code == :refused
    assert File.read!(plan.path) == "# hand-written\n"

    assert {:ok, _} = Direnv.write(plan, force: true)
    assert File.read!(plan.path) == plan.body
  end

  test "members adds each checkout of a workspace", %{
    config: config,
    workspace_path: workspace_path,
    checkout_path: checkout_path
  } do
    assert {:ok, plans} = Direnv.plans(config, "demo@dev", members: true)

    assert plans |> Enum.map(& &1.path) |> Enum.sort() ==
             Enum.sort([
               Path.join(workspace_path, ".envrc"),
               Path.join(checkout_path, ".envrc")
             ])
  end

  test "all covers projects, workspaces and checkouts", %{
    config: config,
    project_path: project_path,
    workspace_path: workspace_path,
    checkout_path: checkout_path
  } do
    assert {:ok, plans} = Direnv.plans(config, ".", all: true)

    assert plans |> Enum.map(& &1.path) |> Enum.sort() ==
             Enum.sort([
               Path.join(project_path, ".envrc"),
               Path.join(workspace_path, ".envrc"),
               Path.join(checkout_path, ".envrc")
             ])
  end

  test "CLI prints and writes", %{checkout_path: checkout_path} do
    {output, 0} = cli(["direnv", "demo@dev:a"])
    assert output =~ "# Generated by gitspace. Do not edit."

    {output, 0} = cli(["direnv", "demo@dev:a", "--write"])
    assert output =~ "wrote #{Path.join(checkout_path, ".envrc")}"
    assert output =~ "direnv allow"
  end

  defp cli(args) do
    {code, output} = ExUnit.CaptureIO.with_io(fn -> Gitspace.CLI.run(args) end)
    {output, code}
  end
end
